"""What every part of Tegami's Mail class may rely on.

Mail (tegami_core.py) is assembled from parts kept by subject: Attachments, Invitations,
Accounts and ClaudeHelp. Each uses state and methods another part provides; they are declared
here once so the type checker knows them. Nothing here runs."""

from typing import TYPE_CHECKING, Any


class MailParts:
    ai: Any
    claude_gen: Any
    claude_proc: Any
    claude_session: Any
    host: Any
    store: Any
    sync: Any

    if TYPE_CHECKING:

        def _invite_public(self, acct: Any, folder: Any, uid: Any) -> Any: ...
        def act(self, actions: Any) -> Any: ...
        def add_account(self, d: Any) -> Any: ...
        def answer_invite(self, key: Any, answer: Any) -> Any: ...
        def ask_claude(self, text: Any, key: Any, shown: Any) -> Any: ...
        def google_sign_in(self, hint: Any = ...) -> Any: ...
        def invitations(self, acct: Any = ...) -> Any: ...
        def js(self, fn: Any, payload: Any = ...) -> Any: ...
        def later(self, f: Any, *args: Any) -> Any: ...
        def open_file(self, key: Any, index: Any, save: Any = ...) -> Any: ...
        def preview(self, key: Any, index: Any) -> Any: ...
        def push_accounts(self) -> Any: ...
        def push_providers(self) -> Any: ...
        def queue(self, d: Any) -> Any: ...
        def read(self, key: Any) -> Any: ...
        def remove_account(self, acct_id: Any) -> Any: ...
        def restart_claude(self) -> Any: ...
        def scan_invites(self) -> Any: ...
        def sort_sender(self, addr: Any, cat: Any) -> Any: ...
        def write_for_me(self, kind: Any, d: Any) -> Any: ...
